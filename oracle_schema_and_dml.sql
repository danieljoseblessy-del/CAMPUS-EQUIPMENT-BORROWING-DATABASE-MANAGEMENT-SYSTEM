-- CAMPUS EQUIPMENT BORROWING SYSTEM
-- Oracle SQL*Plus compatible DDL

BEGIN
  FOR r IN (SELECT table_name FROM user_tables WHERE table_name IN
  ('PAYMENT','FINE','MAINTENANCE','CONDITION_HISTORY','APPROVAL','RESERVATION',
   'BORROWING_ITEM','BORROWING','EQUIPMENT','EQUIPMENT_CATEGORY','STUDENT','DEPARTMENT'))
  LOOP
   EXECUTE IMMEDIATE 'DROP TABLE '||r.table_name||' CASCADE CONSTRAINTS PURGE';
  END LOOP;
 EXCEPTION WHEN OTHERS THEN NULL;
 END;
 /
 
 CREATE TABLE DEPARTMENT (
  department_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
  department_name VARCHAR2(100) NOT NULL,
  building VARCHAR2(100),
  CONSTRAINT pk_department PRIMARY KEY(department_id),
  CONSTRAINT uq_department_name UNIQUE(department_name)
 );
 
 CREATE TABLE STUDENT (
  student_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
  student_name VARCHAR2(100) NOT NULL,
  email VARCHAR2(150) NOT NULL,
  phone VARCHAR2(20),
  department_id NUMBER NOT NULL,
  CONSTRAINT pk_student PRIMARY KEY(student_id),
  CONSTRAINT uq_student_email UNIQUE(email),
  CONSTRAINT fk_student_department FOREIGN KEY(department_id) REFERENCES DEPARTMENT(department_id)
 );
 
 CREATE TABLE EQUIPMENT_CATEGORY (
  category_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
  category_name VARCHAR2(100) NOT NULL,
  description VARCHAR2(250),
  CONSTRAINT pk_equipment_category PRIMARY KEY(category_id),
  CONSTRAINT uq_category_name UNIQUE(category_name)
 );
 
 CREATE TABLE EQUIPMENT (
  equipment_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
  category_id NUMBER NOT NULL,
  equipment_name VARCHAR2(120) NOT NULL,
  asset_tag VARCHAR2(50) NOT NULL,
  serial_no VARCHAR2(80),
  purchase_date DATE,
  availability_status VARCHAR2(20) DEFAULT 'AVAILABLE' NOT NULL,
  current_condition VARCHAR2(20) DEFAULT 'GOOD' NOT NULL,
  CONSTRAINT pk_equipment PRIMARY KEY(equipment_id),
  CONSTRAINT uq_equipment_asset_tag UNIQUE(asset_tag),
  CONSTRAINT uq_equipment_serial_no UNIQUE(serial_no),
  CONSTRAINT fk_equipment_category FOREIGN KEY(category_id) REFERENCES EQUIPMENT_CATEGORY(category_id),
  CONSTRAINT ck_equipment_availability CHECK(availability_status IN
  ('AVAILABLE','BORROWED','RESERVED','DAMAGED','MAINTENANCE')),
  CONSTRAINT ck_equipment_condition CHECK(current_condition IN
  ('EXCELLENT','GOOD','FAIR','DAMAGED','UNUSABLE'))
 );
 
 CREATE TABLE BORROWING (
  borrowing_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
  student_id NUMBER NOT NULL,
  request_date DATE DEFAULT SYSDATE NOT NULL,
  purpose VARCHAR2(250) NOT NULL,
  status VARCHAR2(20) DEFAULT 'REQUESTED' NOT NULL,
  CONSTRAINT pk_borrowing PRIMARY KEY(borrowing_id),
  CONSTRAINT fk_borrowing_student FOREIGN KEY(student_id) REFERENCES STUDENT(student_id),
  CONSTRAINT ck_borrowing_status CHECK(status IN
  ('REQUESTED','APPROVED','ISSUED','RETURNED','CANCELLED'))
 );
 
 CREATE TABLE BORROWING_ITEM (
  borrowing_item_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
  borrowing_id NUMBER NOT NULL,
  equipment_id NUMBER NOT NULL,
  issue_date DATE,
  due_date DATE NOT NULL,
  return_date DATE,
  item_status VARCHAR2(20) DEFAULT 'RESERVED' NOT NULL,
  CONSTRAINT pk_borrowing_item PRIMARY KEY(borrowing_item_id),
  CONSTRAINT fk_item_borrowing FOREIGN KEY(borrowing_id) REFERENCES BORROWING(borrowing_id),
  CONSTRAINT fk_item_equipment FOREIGN KEY(equipment_id) REFERENCES EQUIPMENT(equipment_id),
  CONSTRAINT uq_borrowing_equipment UNIQUE(borrowing_id,equipment_id),
  CONSTRAINT ck_item_status CHECK(item_status IN
  ('RESERVED','ISSUED','RETURNED','LOST','DAMAGED')),
  CONSTRAINT ck_item_dates CHECK(return_date IS NULL OR issue_date IS NULL OR return_date>=issue_date),
  CONSTRAINT ck_due_issue CHECK(issue_date IS NULL OR due_date>=issue_date)
 );
 
 CREATE TABLE RESERVATION (
  reservation_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
  student_id NUMBER NOT NULL,
  equipment_id NUMBER NOT NULL,
  start_time TIMESTAMP NOT NULL,
  end_time TIMESTAMP NOT NULL,
  status VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
  CONSTRAINT pk_reservation PRIMARY KEY(reservation_id),
  CONSTRAINT fk_reservation_student FOREIGN KEY(student_id) REFERENCES STUDENT(student_id),
  CONSTRAINT fk_reservation_equipment FOREIGN KEY(equipment_id) REFERENCES EQUIPMENT(equipment_id),
  CONSTRAINT ck_reservation_status CHECK(status IN
  ('PENDING','CONFIRMED','CANCELLED','COMPLETED')),
  CONSTRAINT ck_reservation_time CHECK(end_time>start_time)
 );
 
 CREATE TABLE APPROVAL (
  approval_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
  borrowing_id NUMBER NOT NULL,
  approved_by VARCHAR2(100) NOT NULL,
  approval_date DATE DEFAULT SYSDATE NOT NULL,
  decision VARCHAR2(20) NOT NULL,
  remarks VARCHAR2(250),
  CONSTRAINT pk_approval PRIMARY KEY(approval_id),
  CONSTRAINT uq_approval_borrowing UNIQUE(borrowing_id),
  CONSTRAINT fk_approval_borrowing FOREIGN KEY(borrowing_id) REFERENCES BORROWING(borrowing_id),
  CONSTRAINT ck_approval_decision CHECK(decision IN('APPROVED','REJECTED'))
 );
 
 CREATE TABLE CONDITION_HISTORY (
  condition_history_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
  equipment_id NUMBER NOT NULL,
  borrowing_item_id NUMBER,
  condition_status VARCHAR2(20) NOT NULL,
  condition_notes VARCHAR2(250),
  recorded_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  recorded_by VARCHAR2(100) NOT NULL,
  CONSTRAINT pk_condition_history PRIMARY KEY(condition_history_id),
  CONSTRAINT fk_condition_equipment FOREIGN KEY(equipment_id) REFERENCES EQUIPMENT(equipment_id),
  CONSTRAINT fk_condition_item FOREIGN KEY(borrowing_item_id) REFERENCES BORROWING_ITEM(borrowing_item_id),
  CONSTRAINT ck_condition_status CHECK(condition_status IN
  ('EXCELLENT','GOOD','FAIR','DAMAGED','UNUSABLE'))
 );
 
 CREATE TABLE MAINTENANCE (
  maintenance_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
  equipment_id NUMBER NOT NULL,
  reported_date DATE DEFAULT SYSDATE NOT NULL,
  maintenance_type VARCHAR2(30) NOT NULL,
  description VARCHAR2(250) NOT NULL,
  completion_date DATE,
  status VARCHAR2(20) DEFAULT 'OPEN' NOT NULL,
  CONSTRAINT pk_maintenance PRIMARY KEY(maintenance_id),
  CONSTRAINT fk_maintenance_equipment FOREIGN KEY(equipment_id) REFERENCES EQUIPMENT(equipment_id),
  CONSTRAINT ck_maintenance_type CHECK(maintenance_type IN
  ('REPAIR','PREVENTIVE','INSPECTION','CALIBRATION')),
  CONSTRAINT ck_maintenance_status CHECK(status IN('OPEN','IN_PROGRESS','COMPLETED')),
  CONSTRAINT ck_maintenance_dates CHECK(completion_date IS NULL OR completion_date>=reported_date)
 );
 
 CREATE TABLE FINE (
  fine_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
  borrowing_item_id NUMBER NOT NULL,
  amount NUMBER(10,2) NOT NULL,
  reason VARCHAR2(250) NOT NULL,
  assessed_date DATE DEFAULT SYSDATE NOT NULL,
  payment_status VARCHAR2(20) DEFAULT 'UNPAID' NOT NULL,
  CONSTRAINT pk_fine PRIMARY KEY(fine_id),
  CONSTRAINT uq_fine_item UNIQUE(borrowing_item_id),
  CONSTRAINT fk_fine_item FOREIGN KEY(borrowing_item_id) REFERENCES BORROWING_ITEM(borrowing_item_id),
  CONSTRAINT ck_fine_amount CHECK(amount>=0),
  CONSTRAINT ck_fine_payment_status CHECK(payment_status IN('UNPAID','PAID','WAIVED'))
 );
 
 CREATE TABLE PAYMENT (
  payment_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
  fine_id NUMBER NOT NULL,
  amount NUMBER(10,2) NOT NULL,
  payment_date DATE DEFAULT SYSDATE NOT NULL,
  payment_method VARCHAR2(20) NOT NULL,
  CONSTRAINT pk_payment PRIMARY KEY(payment_id),
  CONSTRAINT uq_payment_fine UNIQUE(fine_id),
  CONSTRAINT fk_payment_fine FOREIGN KEY(fine_id) REFERENCES FINE(fine_id),
  CONSTRAINT ck_payment_amount CHECK(amount>0),
  CONSTRAINT ck_payment_method CHECK(payment_method IN('CASH','CARD','UPI','ONLINE'))
 );
 
 SELECT table_name FROM user_tables
 WHERE table_name IN('STUDENT','DEPARTMENT','EQUIPMENT','EQUIPMENT_CATEGORY',
 'BORROWING','BORROWING_ITEM','RESERVATION','APPROVAL','CONDITION_HISTORY',
 'MAINTENANCE','FINE','PAYMENT') ORDER BY table_name;
 
 SELECT constraint_name,table_name,constraint_type
 FROM user_constraints
 WHERE table_name IN('STUDENT','DEPARTMENT','EQUIPMENT','EQUIPMENT_CATEGORY',
 'BORROWING','BORROWING_ITEM','RESERVATION','APPROVAL','CONDITION_HISTORY',
 'MAINTENANCE','FINE','PAYMENT') ORDER BY table_name,constraint_name;

