CREATE TABLE EQUIPMENT_CATEGORY
(
    category_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR2(100) NOT NULL UNIQUE,
    description VARCHAR2(250)
)
/

CREATE TABLE EQUIPMENT
(
    equipment_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    
    category_id NUMBER NOT NULL
        REFERENCES EQUIPMENT_CATEGORY(category_id),
    
    equipment_name VARCHAR2(120) NOT NULL,
    asset_tag VARCHAR2(50) NOT NULL UNIQUE,
    serial_no VARCHAR2(80) UNIQUE,
    purchase_date DATE,
    
    availability_status VARCHAR2(20)
        DEFAULT 'AVAILABLE'
        NOT NULL
        CHECK (
            availability_status IN
            ('AVAILABLE',
             'BORROWED',
             'RESERVED',
             'DAMAGED',
             'MAINTENANCE')
        ),
    
    current_condition VARCHAR2(20)
        DEFAULT 'GOOD'
        NOT NULL
        CHECK (
            current_condition IN
            ('EXCELLENT',
             'GOOD',
             'FAIR',
             'DAMAGED',
             'UNUSABLE')
        )
)
/

CREATE TABLE BORROWING
(
    borrowing_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    
    student_id NUMBER NOT NULL
        REFERENCES STUDENT(student_id),
    
    request_date DATE DEFAULT SYSDATE NOT NULL,
    purpose VARCHAR2(250) NOT NULL,
    
    status VARCHAR2(20)
        DEFAULT 'REQUESTED'
        NOT NULL
        CHECK (
            status IN
            ('REQUESTED',
             'APPROVED',
             'ISSUED',
             'RETURNED',
             'CANCELLED')
        )
)
/

CREATE TABLE BORROWING_ITEM
(
    borrowing_item_id NUMBER
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,
    
    borrowing_id NUMBER NOT NULL
        REFERENCES BORROWING(borrowing_id),
    
    equipment_id NUMBER NOT NULL
        REFERENCES EQUIPMENT(equipment_id),
    
    issue_date DATE,
    due_date DATE NOT NULL,
    return_date DATE,
    
    item_status VARCHAR2(20)
        DEFAULT 'RESERVED'
        NOT NULL
        CHECK (
            item_status IN
            ('RESERVED',
             'ISSUED',
             'RETURNED',
             'LOST',
             'DAMAGED')
        ),
    
    CHECK (
        return_date IS NULL
        OR issue_date IS NULL
        OR return_date >= issue_date
    ),
    
    CHECK (
        issue_date IS NULL
        OR due_date >= issue_date
    ),
    
    UNIQUE (borrowing_id, equipment_id)
)
/

CREATE TABLE RESERVATION
(
    reservation_id NUMBER
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,
    
    student_id NUMBER NOT NULL
        REFERENCES STUDENT(student_id),
    
    equipment_id NUMBER NOT NULL
        REFERENCES EQUIPMENT(equipment_id),
    
    start_time TIMESTAMP NOT NULL,
    end_time TIMESTAMP NOT NULL,
    
    status VARCHAR2(20)
        DEFAULT 'PENDING'
        NOT NULL
        CHECK (
            status IN
            ('PENDING',
             'CONFIRMED',
             'CANCELLED',
             'COMPLETED')
        ),
    
    CHECK (end_time > start_time)
)
/

CREATE TABLE APPROVAL
(
    approval_id NUMBER
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,
    
    borrowing_id NUMBER NOT NULL
        REFERENCES BORROWING(borrowing_id)
        UNIQUE,
    
    approved_by VARCHAR2(100) NOT NULL,
    approval_date DATE DEFAULT SYSDATE NOT NULL,
    
    decision VARCHAR2(20)
        NOT NULL
        CHECK (
            decision IN
            ('APPROVED',
             'REJECTED')
        ),
    
    remarks VARCHAR2(250)
)
/

CREATE TABLE CONDITION_HISTORY
(
    condition_history_id NUMBER
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,
    
    equipment_id NUMBER NOT NULL
        REFERENCES EQUIPMENT(equipment_id),
    
    borrowing_item_id NUMBER
        REFERENCES BORROWING_ITEM(borrowing_item_id),
    
    condition_status VARCHAR2(20)
        NOT NULL
        CHECK (
            condition_status IN
            ('EXCELLENT',
             'GOOD',
             'FAIR',
             'DAMAGED',
             'UNUSABLE')
        ),
    
    condition_notes VARCHAR2(250),
    
    recorded_at TIMESTAMP
        DEFAULT SYSTIMESTAMP
        NOT NULL,
    
    recorded_by VARCHAR2(100) NOT NULL
)
/

CREATE TABLE MAINTENANCE
(
    maintenance_id NUMBER
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,
    
    equipment_id NUMBER NOT NULL
        REFERENCES EQUIPMENT(equipment_id),
    
    reported_date DATE
        DEFAULT SYSDATE
        NOT NULL,
    
    maintenance_type VARCHAR2(30)
        NOT NULL
        CHECK (
            maintenance_type IN
            ('REPAIR',
             'PREVENTIVE',
             'INSPECTION',
             'CALIBRATION')
        ),
    
    description VARCHAR2(250) NOT NULL,
    
    completion_date DATE,
    
    status VARCHAR2(20)
        DEFAULT 'OPEN'
        NOT NULL
        CHECK (
            status IN
            ('OPEN',
             'IN_PROGRESS',
             'COMPLETED')
        ),
    
    CHECK (
        completion_date IS NULL
        OR completion_date >= reported_date
    )
)
/

CREATE TABLE FINE
(
    fine_id NUMBER
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,
    
    borrowing_item_id NUMBER NOT NULL
        REFERENCES BORROWING_ITEM(borrowing_item_id)
        UNIQUE,
    
    amount NUMBER(10,2)
        NOT NULL
        CHECK (amount >= 0),
    
    reason VARCHAR2(250) NOT NULL,
    
    assessed_date DATE
        DEFAULT SYSDATE
        NOT NULL,
    
    payment_status VARCHAR2(20)
        DEFAULT 'UNPAID'
        NOT NULL
        CHECK (
            payment_status IN
            ('UNPAID',
             'PAID',
             'WAIVED')
        )
)
/

CREATE TABLE PAYMENT
(
    payment_id NUMBER
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,
    
    fine_id NUMBER NOT NULL
        REFERENCES FINE(fine_id)
        UNIQUE,
    
    amount NUMBER(10,2)
        NOT NULL
        CHECK (amount > 0),
    
    payment_date DATE
        DEFAULT SYSDATE
        NOT NULL,
    
    payment_method VARCHAR2(20)
        NOT NULL
        CHECK (
            payment_method IN
            ('CASH',
             'CARD',
             'UPI',
             'ONLINE')
        )
)
/