FROM user_tables
WHERE table_name IN (
 'DEPARTMENT','STUDENT','EQUIPMENT_CATEGORY','EQUIPMENT',
 'BORROWING','BORROWING_ITEM','RESERVATION','APPROVAL',
 'CONDITION_HISTORY','MAINTENANCE','FINE','PAYMENT'
)
ORDER BY table_name;

